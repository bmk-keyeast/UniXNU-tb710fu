#!/usr/bin/env python3
"""Generate dts/tb710fu.dts from the mainline Linux TB710FU device tree.

The reserved-memory map comes from the compiled mainline DTB
(arch/arm64/boot/dts/qcom/sm8650-lenovo-tb710fu.dtb), which merges the
sm8650.dtsi regions with the board's own overrides (rmtfs, hwfence, ...).

usage: gen-board-dts.py LINUX_DTB [--dtc PATH] [--ram-gib N] > dts/tb710fu.dts
       gen-board-dts.py --selftest
"""
import argparse
import re
import subprocess
import sys

NODE = re.compile(r"^\t\t([\w,.+-]+)@([0-9a-f]+) \{$")
REG = re.compile(r"^\t\t\treg = <((?:0x[0-9a-f]+ ?)+)>;$")


def reserved_regions(dts_text):
    """Yield (name, addr, size, no_map) for each /reserved-memory child with a reg."""
    lines = dts_text.splitlines()
    try:
        start = lines.index("\treserved-memory {")
    except ValueError:
        sys.exit("no /reserved-memory node in the DTB")
    name = addr = reg = None
    no_map = False
    for line in lines[start + 1:]:
        if line == "\t};":
            break
        m = NODE.match(line)
        if m:
            name, addr, reg, no_map = m.group(1), int(m.group(2), 16), None, False
            continue
        m = REG.match(line)
        if m and name:
            cells = [int(c, 16) for c in m.group(1).split()]
            reg = ((cells[0] << 32) | cells[1], (cells[2] << 32) | cells[3])
        if line == "\t\t\tno-map;":
            no_map = True
        if line == "\t\t};" and name:
            if reg:  # dynamic pools (linux,cma) have no reg: skip
                yield name, reg[0], reg[1], no_map
            name = None


def render(regions, ram_gib):
    out = [
        "// SPDX-License-Identifier: BSD-3-Clause",
        "// Lenovo Xiaoxin Pad Pro GT (TB710FU) board device tree for UniXNU.",
        "// GENERATED by scripts/gen-board-dts.py from the mainline Linux DTB",
        "// (sm8650-lenovo-tb710fu.dtb). Do not edit the reserved-memory block by hand.",
        "/dts-v1/;",
        '/include/ "sm8650.dtsi"',
        "",
        "/ {",
        '    model = "Lenovo Xiaoxin Pad Pro GT (TB710FU)";',
        '    compatible = "lenovo,tb710fu", "qcom,sm8650";',
        "",
        "    // ABL rewrites the real bank layout at boot; the ADT needs a static size.",
        f"    // {ram_gib} GiB SKU. Confirm with: adb shell cat /proc/meminfo",
        "    memory@80000000 {",
        '        device_type = "memory";',
        f"        reg = <0 0x80000000 {ram_gib >> 2} {(ram_gib & 3) << 30:#x}>;",
        "    };",
        "",
        "    reserved-memory {",
        "        #address-cells = <2>;",
        "        #size-cells = <2>;",
        "        ranges;",
        "",
    ]
    for name, addr, size, no_map in sorted(regions, key=lambda r: r[1]):
        flag = " no-map;" if no_map else ""
        out.append(f"        {name}@{addr:x} {{ reg = <0 {addr:#x} 0 {size:#x}>;{flag} }};")
    out += [
        "    };",
        "};",
        "",
        "// SM8650 CPU topology: 2x A520 (E), 5x A720 (P), 1x X4 (P) -- see sm8650.dtsi.",
    ]
    out += [f'&cpu{i} {{ unixnu,cluster-type = "{"E" if i < 2 else "P"}"; }};' for i in range(8)]
    out += ['&ufs { status = "okay"; };', '&ufsphy { status = "okay"; };', ""]
    return "\n".join(out)


SAMPLE = """\
/ {
\treserved-memory {
\t\t#address-cells = <0x02>;

\t\thyp@80000000 {
\t\t\treg = <0x00 0x80000000 0x00 0xe00000>;
\t\t\tno-map;
\t\t};

\t\tlinux,cma {
\t\t\tcompatible = "shared-dma-pool";
\t\t\tsize = <0x00 0x2000000>;
\t\t};

\t\tramoops@ac300000 {
\t\t\tcompatible = "ramoops";
\t\t\treg = <0x00 0xac300000 0x00 0x100000>;
\t\t};
\t};
};
"""


def selftest():
    got = list(reserved_regions(SAMPLE))
    assert got == [("hyp", 0x80000000, 0xE00000, True), ("ramoops", 0xAC300000, 0x100000, False)], got
    dts = render(got, 12)
    assert "reg = <0 0x80000000 3 0x0>;" in dts, dts  # 12 GiB = 0x3_0000_0000
    assert "hyp@80000000 { reg = <0 0x80000000 0 0xe00000>; no-map; };" in dts
    assert "ramoops@ac300000 { reg = <0 0xac300000 0 0x100000>; };" in dts
    assert "reg = <0 0x80000000 4 0x0>;" in render(got, 16)
    print("selftest ok")


def main():
    p = argparse.ArgumentParser()
    p.add_argument("dtb", nargs="?")
    p.add_argument("--dtc", default="dtc")
    p.add_argument("--ram-gib", type=int, default=12)
    p.add_argument("--selftest", action="store_true")
    a = p.parse_args()
    if a.selftest:
        return selftest()
    if not a.dtb:
        p.error("LINUX_DTB is required")
    text = subprocess.run([a.dtc, "-q", "-I", "dtb", "-O", "dts", a.dtb],
                          check=True, capture_output=True, text=True).stdout
    sys.stdout.write(render(list(reserved_regions(text)), a.ram_gib))


if __name__ == "__main__":
    main()
